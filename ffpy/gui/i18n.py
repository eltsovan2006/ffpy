import sys

_LANG = None


def language():
    global _LANG
    if _LANG is None:
        try:
            from PySide6.QtCore import QSettings
            _LANG = str(QSettings("ffpy", "ffpy-gui").value("language", "ru"))
        except Exception:
            _LANG = "ru"
    return _LANG


def tr(text):
    if language() != "en":
        return text
    return EN.get(text, text)


