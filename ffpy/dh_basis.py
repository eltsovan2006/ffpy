# polarization exponents: POLAR=DUNNING column; blank entries equal the POPLE column
D_EXP = {"C": 0.75, "Al": 0.325, "Si": 0.395, "P": 0.55, "S": 0.65, "Cl": 0.75}
P_EXP = {"H": 1.0}


def shells(element, inner=1.2, outer=1.15):
    """DH shells of an element; hydrogen exponents are scaled by inner**2 / outer**2 (Firefly's
    default scale factors are 1.2 and 1.15)."""
    import copy
    if element not in DZ:
        raise ValueError("the Dunning-Hay basis is not available for %s" % element)
    sh = copy.deepcopy(DZ[element])
    if element == "H":
        for shell, f in zip(sh, (inner ** 2, outer ** 2)):
            for prim in shell[1:]:
                prim[0] *= f
    return sh
